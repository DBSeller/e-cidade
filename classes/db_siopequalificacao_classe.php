       $this->erro_status = "0";
       return false;
     }
     $sql = "insert into siopequalificacao(
                                       si04_id 
                                      ,si04_descricao 
                       )
                values (
                                $this->si04_id 
                               ,'$this->si04_descricao' 
                      )";
     $result = db_query($sql); 
