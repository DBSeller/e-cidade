       $this->si01_id = ($this->si01_id == ""?@$GLOBALS["HTTP_POST_VARS"]["si01_id"]:$this->si01_id);
     }
   }

    public function incluir($si01_id)
    {
      $this->atualizacampos();
     if($this->si01_descricao == null ){ 
       $this->erro_sql = " Campo Situação não informado.";
       $this->erro_campo = "si01_descricao";
       $this->erro_banco = "";
       $this->erro_msg   = "Usuário: \\n\\n ".$this->erro_sql." \\n\\n";
       $this->erro_msg   .=  str_replace('"',"",str_replace("'","",  "Administrador: \\n\\n ".$this->erro_banco." \\n"));
       $this->erro_status = "0";
       return false;
     }
     if($si01_id == "" || $si01_id == null ){
       $result = db_query("select nextval('siopesituacao_id_seq')"); 
       if($result==false){
         $this->erro_banco = str_replace("\n","",@pg_last_error());
         $this->erro_sql   = "Verifique o cadastro da sequencia: siopesituacao_id_seq do campo: si01_id"; 
